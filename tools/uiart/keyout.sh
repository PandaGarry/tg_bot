#!/bin/bash
# Вырезание фона у сгенерированной иконки и приведение к 256×256 с прозрачностью.
#
#   keyout.sh <вход> <выход> [доп. преобразование, например -flop]
#
# Модель рисует на ровном светлом фоне и не даёт альфа-канал. Простое вырезание
# заливкой оставляет по краю светлую кайму в полпикселя — на тёмном интерфейсе
# она видна как «иконка на белом». Поэтому после заливки край сжимается эрозией
# на полном размере (3 px из 1254 — не заметно), и только потом иконка уменьшается:
# в альфе остаются только собственные пиксели знака, каймы нет.
set -e
src="$1"; out="$2"; extra="$3"
convert "$src" -alpha set -fuzz 12% -fill none -draw "color 0,0 floodfill" $extra \
  -channel A -morphology Erode Disk:3 +channel \
  -channel A -blur 0x2.5 +channel \
  -trim +repage -resize 232x232 -background none -gravity center -extent 256x256 \
  -strip PNG32:"$out"
